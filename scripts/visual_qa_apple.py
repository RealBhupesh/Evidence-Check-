from playwright.sync_api import sync_playwright
from pathlib import Path
root=Path(__file__).resolve().parent.parent
html=(root/'showcase/EvidenceCheck_Standalone_Demo.html').read_text()
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True, executable_path='/usr/bin/chromium', args=['--no-sandbox','--no-proxy-server'])
    page=browser.new_page(viewport={'width':1440,'height':900},device_scale_factor=1)
    issues=[]
    page.on('pageerror',lambda e:issues.append('PAGEERROR: '+str(e)))
    page.on('console', lambda m: issues.append('CONSOLE '+m.type+': '+m.text) if m.type=='error' else None)
    page.set_content(html, wait_until='load')
    page.wait_for_selector('#stat-total:text("14")',timeout=12000)
    print('desktop stats', [page.locator('#'+x).inner_text() for x in ['stat-total','stat-match','stat-issues','stat-review']])
    page.screenshot(path='/mnt/data/EvidenceCheck_Apple_Desktop.png')
    page.locator('#hero-try-sample').click()
    page.wait_for_timeout(500)
    page.screenshot(path='/mnt/data/EvidenceCheck_Apple_Workspace.png',full_page=False)
    print('hero goes to workspace',page.locator('#claim-input').evaluate('(el)=>document.activeElement===el'))
    page.locator('#claim-input').fill('Apple FY2025 revenue was $416.161 billion.\nApple FY2025 net income was $200 billion.')
    page.locator('#run-audit').click()
    page.wait_for_timeout(350)
    print('modified stats',[page.locator('#'+x).inner_text() for x in ['stat-total','stat-match','stat-issues','stat-review']])
    page.locator('#claim-input').fill('Apple FY2025 revenue was $416.161 billion.')
    print('stale guard',page.locator('#download-csv').is_disabled(),page.locator('#stat-total').inner_text())
    page.locator('#claim-input').press('Control+Enter')
    page.wait_for_timeout(300)
    print('keyboard shortcut verified',page.locator('#stat-total').inner_text())
    page.locator('[data-nav="library"]').click()
    print('library count',page.locator('.facts-table tbody tr').count())
    page.locator('#filter-company').select_option('MSFT')
    print('filtered',page.locator('#filter-count').inner_text())
    page.screenshot(path='/mnt/data/EvidenceCheck_Apple_Library.png',full_page=False)
    page.locator('[data-nav="method"]').click()
    print('method displayed',page.locator('#method').is_visible())
    print('desktop horizontal scroll',page.evaluate('document.documentElement.scrollWidth > window.innerWidth'))
    page2=browser.new_page(viewport={'width':390,'height':844},device_scale_factor=1, is_mobile=True,has_touch=True)
    page2.on('pageerror',lambda e:issues.append('MOBILE PAGEERROR: '+str(e)))
    page2.set_content(html, wait_until='load')
    page2.wait_for_selector('#stat-total:text("14")',timeout=12000)
    page2.screenshot(path='/mnt/data/EvidenceCheck_Apple_Mobile.png')
    print('mobile horizontal scroll',page2.evaluate('document.documentElement.scrollWidth > window.innerWidth'), 'content width',page2.evaluate('document.documentElement.scrollWidth'))
    page2.locator('[data-nav="library"]').click()
    print('mobile library',page2.locator('.facts-table tbody tr').count())
    print('console/errors',issues)
    browser.close()
